// SessionReadme — writes <dir>/readme.md for one session or task folder, computed from its own record (CLAUDE.md law 7: no AI recall).
// usage: node Server/SessionReadme.mjs <folder> [--print]      (the proposal and the format: public/framework/ai/sessions/doc/session-readme.md)
import fs from "node:fs";
import path from "node:path";
import SessionRecord from "./SessionRecord.mjs";

const ROOT = path.resolve(import.meta.dirname, "..");
const ASKS = path.join(ROOT, "public/framework/ai/asks.jsonl");
const rows = file => !file || !fs.existsSync(file) ? [] : fs.readFileSync(file, "utf8").split(/\r?\n/).filter(Boolean).flatMap(l => { try { return [JSON.parse(l)]; } catch { return []; } });
const verb = o => Object.keys(o ?? {})[0];
const cell = s => String(s ?? "").replace(/\s+/g, " ").replace(/\|/g, "/").trim();

export default class SessionReadme {
	static FILES = { "requirements.md": "the brief this folder was started with", "report.md": "what the work found or built", "past-work.md": "earlier work on the same topic (Server/PastWork.mjs)", "session.md": "the session's own note" };

	constructor(dir){ this.dir = path.resolve(dir); this.file = SessionRecord.file(this.dir); this.lines = rows(this.file); }

	get first(){ const l = this.lines[0] ?? {}; return l.assign ?? l.session ?? {}; }
	count(v){ return this.lines.filter(l => verb(l) === v).length; }
	get commits(){ return this.lines.filter(l => "commit" in l).map(l => typeof l.commit === "string" ? l.commit : l.commit?.sha ?? l.commit?.hash).filter(Boolean); }
	get landed(){ return this.lines.map(l => l.assign?.landed_at ?? l.landed_at).filter(Boolean).pop() ?? null; }
	get logs(){ return this.lines.filter(l => l.log?.msg).map(l => `${(l.log.at ?? "").slice(0, 16).replace("T", " ")} ${cell(l.log.msg)}`); }

	/* Asks that name this folder: the ledger row's `card`/`task` is inside this path, or its `owner` is this folder's agent. */
	get asks(){
		const rel = path.relative(path.join(ROOT, "public/framework/ai/sessions"), this.dir).replaceAll("\\", "/"), agent = this.first.agent;
		const mine = new Map();
		for (const { ask } of rows(ASKS)) if (ask?.id && (ask.card && rel.includes(ask.card) || ask.task && rel.endsWith(ask.task) || agent && ask.owner === agent)) mine.set(ask.id, { ...mine.get(ask.id), ...ask });
		return [...mine.values()];
	}

	markdown(){
		const f = this.first, name = path.basename(this.dir), out = [];
		out.push(`# ${cell(f.title) || name}`, "", `Generated by \`node Server/SessionReadme.mjs\` from \`${path.basename(this.file ?? "no record")}\`. Do not edit; run it again. [Format](/framework/ai/sessions/doc/session-readme.md).`, "");
		out.push("| | |", "|---|---|");
		for (const [k, v] of [["agent", f.agent], ["kind", f.kind], ["caller", f.caller], ["model", f.model], ["session id", f.session_id ?? f.id], ["requested", f.requested_at ?? (f.at && new Date(f.at).toISOString())], ["home", f.home], ["landed", this.landed], ["lines in the record", this.lines.length]])
			if (v) out.push(`| ${k} | ${cell(v)} |`);
		out.push("", `**Counts:** ${["log", "action", "commit", "decision", "chat", "owner_words", "tool_call", "spawned"].map(v => [v, this.count(v)]).filter(([, n]) => n).map(([v, n]) => `${n} ${v}`).join(" · ") || "none"}.`);
		if (this.commits.length) out.push("", `**Commits:** ${this.commits.map(c => `\`${String(c).slice(0, 9)}\``).join(" ")}`);
		const asks = this.asks;
		if (asks.length) out.push("", "## Asks that name this folder", "", "| status | title | owner |", "|---|---|---|", ...asks.map(a => `| ${cell(a.status)} | ${cell(a.title ?? a.why ?? a.id)} | ${cell(a.owner)} |`));
		const here = fs.readdirSync(this.dir, { withFileTypes: true }).filter(e => e.name !== "readme.md");
		out.push("", "## In this folder", "", ...here.map(e => `- [${e.name}${e.isDirectory() ? "/" : ""}](${e.name}${e.isDirectory() ? "/" : ""})${SessionReadme.FILES[e.name] ? ` — ${SessionReadme.FILES[e.name]}` : ""}`));
		const logs = this.logs.slice(-5);
		if (logs.length) out.push("", "## Last log lines", "", ...logs.map(l => `- ${l}`));
		return out.join("\n") + "\n";
	}

	write(){ fs.writeFileSync(path.join(this.dir, "readme.md"), this.markdown()); return path.join(this.dir, "readme.md"); }
}

if (process.argv[1] && path.resolve(process.argv[1]) === import.meta.filename){
	const [dir, flag] = process.argv.slice(2);
	if (!dir){ console.error("usage: node Server/SessionReadme.mjs <folder> [--print]"); process.exit(2); }
	const r = new SessionReadme(dir);
	if (flag === "--print") process.stdout.write(r.markdown()); else console.log("wrote", r.write());
}
