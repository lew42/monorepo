// Maps every skill and role and counts its use. Rerun: node Servex/doc/skills-and-roles.mjs
// Writes Servex/doc/skills-and-roles.json (the numbers) and prints the two tables as markdown.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const DAY = 86400000;
const now = Date.now();
const home = process.env.SERVEX_HOME || path.join(process.env.LOCALAPPDATA || path.join(os.homedir(), ".local", "share"), "lew42", "servex");
const servexLog = path.join(home, "logs", "skills.jsonl");

const used = new Map();   // name -> { kind, n7, n30, n_all, last, source }
const bump = (name, kind, at, source) => {
	const u = used.get(name) ?? { name, kind, n7: 0, n30: 0, n_all: 0, last: null, source: new Set() };
	const t = at ? Date.parse(at) : NaN;
	u.n_all++;
	if (!Number.isNaN(t)) {
		if (now - t <= 7 * DAY) u.n7++;
		if (now - t <= 30 * DAY) u.n30++;
		if (!u.last || t > Date.parse(u.last)) u.last = at;
	}
	u.source.add(source);
	used.set(name, u);
};

// 1. Skill calls: ledger.mjs writes {"log":{"at","msg":"skill: <name>"}} into the active task.jsonl.
const walk = function* (dir) {
	let entries;
	try { entries = fs.readdirSync(dir, { withFileTypes: true }); } catch { return; }
	for (const e of entries) {
		const p = path.join(dir, e.name);
		if (e.isDirectory()) { if (e.name !== "node_modules" && e.name[0] !== ".") yield* walk(p); }
		else if (e.name === "task.jsonl" || e.name === "session.jsonl") yield p;
	}
};
for (const file of walk(path.join(root, "public"))) {
	for (const raw of fs.readFileSync(file, "utf8").split("\n")) {
		if (!raw.includes('"skill: ')) continue;
		let o; try { o = JSON.parse(raw); } catch { continue; }
		const m = /^skill: ([a-z0-9:-]+)$/.exec(o.log?.msg ?? "");
		if (m) bump(m[1].trim(), "skill", o.log.at, "task.jsonl log (ledger.mjs)");
	}
}

// 2. Role spawns and inlined skills: Servex writes one `skills` line per spawn into its own log (outside the repo).
let servexLines = 0, servexFirst = null;
if (fs.existsSync(servexLog)) {
	for (const raw of fs.readFileSync(servexLog, "utf8").split("\n")) {
		if (!raw.trim()) continue;
		let o; try { o = JSON.parse(raw); } catch { continue; }
		servexLines++;
		servexFirst ??= o.at;
		if (o.role) bump(o.role, "role", o.at, "Servex skills log (spawn)");
		for (const s of o.injected ?? []) { const r = /^roles\/([a-z0-9-]+)$/.exec(s); if (r) bump(r[1], "role", o.at, "Servex skills log (inlined role text)"); else bump(s, "skill", o.at, "Servex skills log (inlined)"); }
	}
}

// 3. The catalogue: skill folders and the role table.
const skillDirs = fs.readdirSync(path.join(root, ".claude/skills"), { withFileTypes: true })
	.filter(e => e.isDirectory() && fs.existsSync(path.join(root, ".claude/skills", e.name, "SKILL.md")))
	.map(e => e.name).sort();
const roleFiles = fs.readdirSync(path.join(root, "Servex/agents/roles")).filter(f => f.endsWith(".md") && f !== "readme.md").map(f => f.slice(0, -3));
const rolesJs = fs.readFileSync(path.join(root, "Servex/agents/roles.js"), "utf8");
const roleRows = [...rolesJs.matchAll(/^\t"?([a-z][a-z0-9-]*)"?:\s*\{/gm)].map(m => m[1]);
const roleNames = [...new Set([...roleRows, ...roleFiles])].sort();

const rows = [];
for (const name of skillDirs) {
	const u = used.get(name);
	rows.push({ name, kind: "skill", n7: u?.n7 ?? 0, n30: u?.n30 ?? 0, n_all: u?.n_all ?? 0, last: u?.last ?? null, source: u ? [...u.source].join("; ") : "none in logs" });
}
for (const name of roleNames) {
	const u = used.get(name);
	rows.push({ name, kind: "role", n7: u?.n7 ?? 0, n30: u?.n30 ?? 0, n_all: u?.n_all ?? 0, last: u?.last ?? null, source: u ? [...u.source].join("; ") : "none in logs" });
}
for (const [name, u] of used) if (!rows.some(r => r.name === name)) rows.push({ name, kind: u.kind + " (not in catalogue)", n7: u.n7, n30: u.n30, n_all: u.n_all, last: u.last, source: [...u.source].join("; ") });

const retire = rows.filter(r => r.n30 === 0 && !r.kind.includes("not in"));
const notes = { servexLines, servexFirst, skillDirs: skillDirs.length, roles: roleNames.length };
fs.writeFileSync(path.join(root, "Servex/doc/skills-and-roles.json"), JSON.stringify({ at: new Date(now).toISOString(), notes, rows, retire: retire.map(r => r.name) }, null, 2) + "\n");

const cell = v => v ?? "never";
const table = ["| Name | Kind | Last 7 d | Last 30 d | All logged | Last used | Counted from |", "|---|---|---|---|---|---|---|",
	...rows.map(r => `| ${r.name} | ${r.kind} | ${r.n7} | ${r.n30} | ${r.n_all} | ${cell(r.last)} | ${r.source} |`)].join("\n");
const md = `# Skills and roles: what exists and what is used

Generated by \`node Servex/doc/skills-and-roles.mjs\` (run ${new Date(now).toISOString().slice(0, 10)}; the numbers are in \`skills-and-roles.json\`). Rerun it to refresh the counts; the judgment table below is written by hand.

## Where each count comes from

- **Skill calls:** \`.claude/hooks/ledger.mjs\` writes \`{"log":{"at","msg":"skill: <name>"}}\` into the active task's \`task.jsonl\` on every Skill call. The script reads every \`task.jsonl\` and \`session.jsonl\` under \`public/\`. It cannot see a tab or session with no open task (it logs nothing), a plugin skill that is not in the log under its plain name, or any use before the task existed.
- **Role spawns and inlined skills:** Servex appends one \`skills\` line per spawn to \`%LOCALAPPDATA%/lew42/servex/logs/skills.jsonl\` (\`Servex/agents/Agents.js\`): \`role\`, and \`injected\`, the names of the skill and role texts put in the first message. An inlined skill was loaded into the prompt, not necessarily used by the agent. This log is on this PC only and starts at ${servexFirst ?? "n/a"} (${servexLines} lines).
- The 30-day window is therefore really the days since that date for role spawns (about ${Math.max(1, Math.round((now - Date.parse(servexFirst ?? new Date(now).toISOString())) / DAY))} days), and the ledger logs only since each task.jsonl exists.
- The catalogue is the folders in \`.claude/skills/\` that hold a \`SKILL.md\` (${skillDirs.length}) and the rows of the table in \`Servex/agents/roles.js\` plus the files in \`Servex/agents/roles/\` (${roleNames.length} names).

## Every skill and role

${table}

## Proposals (not done: nothing deleted or edited)

Judgment from the table above. Read each row's SKILL.md before acting on it.

| Proposal | Names | Why |
|---|---|---|
| Retire (no use in 30 days) | color, content, navigation, new-css-class, ui, openrouter, fork-claude-session, make, master-assistant, log-assistant, voice-assistant, research, skill-improvement, new-task | No logged call or spawn in 30 days. \`research\` is still named by the \`voter\` row, which has no spawns, so check that row first. \`voice-assistant\` is the live voice skill: keep unless voice is dropped. |
| Merge or fold | sub-mastermind into mastermind; figma (3 uses) into the plugin's figma:figma-use (32) | \`roles/mastermind.md\` says sub-mastermind is only a word for mastermind (folded 2026-10-25), yet the skill is still inlined (183 in 30 days). Two figma skills do the same job. |
| Only records a step (candidate for a tool call) | new-task, finish-task, skill-improvement | Each tells the agent to run a node script or append a line. The hook already writes the skill-call line; a tool would remove a prose step. |

Rows marked "not in catalogue" come from logs only: a skill or role name that no current folder or table row holds (for example \`new-page\`, \`dataviz\`, or names from older sessions).
`;
fs.writeFileSync(path.join(root, "Servex/doc/skills-and-roles.md"), md);
console.log(table);
console.log(`\nno use in 30 days: ${retire.map(r => r.name).join(", ") || "none"}`);
console.log(`Servex skills log: ${servexLines} lines, from ${servexFirst ?? "n/a"} (${servexLog})`);
