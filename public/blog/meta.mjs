/**
 * meta.mjs — stamp each post's static `index.html` from `posts.js`.
 *
 *   node public/blog/meta.mjs            check every shell against the manifest
 *   node public/blog/meta.mjs --write    rewrite them
 *
 * ⚠ This is NOT a build step. It is run by hand when a post is added or its title
 *   changes, and its output is committed — `public/` still runs exactly as it sits on
 *   disk, and the site deploys with no tooling. What it removes is the one thing the
 *   hybrid costs: three strings that would otherwise live in two files and drift.
 *
 * A post with no `index.html` still works — the SPA fallback answers and the post
 * renders with the site's generic meta tags. So `--check` failing is a missing social
 * card, never a broken page. doc/meta-tags.md.
 */
import { readFile, writeFile, stat, readdir } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { listed, sections, slug, site } from "./posts.js";

const here = dirname(fileURLToPath(import.meta.url));
const write = process.argv.includes("--write");

// ⚠ Attribute values, so `"` and `&` are the whole escape set that matters; `<` is
// escaped too because a description is prose somebody typed.
const esc = s => String(s).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");

/* THE SHELL. Deliberately the site's own `index.html` plus a head — same charset-first
 * rule (the deployed host serves no charset header), same `/app.js`, same favicon. */
function shell({ title, description, url, image, type = "article" }){
	const abs = site + url;

	return `<!doctype html>
<html lang="en">
<head>
	<!-- ⚠ GENERATED by blog/meta.mjs from blog/posts.js — edit the manifest, not this file.
	     charset FIRST and inside the first 1024 bytes: the deployed host serves without a
	     charset header, so a document that does not declare one is decoded as Windows-1252. -->
	<meta charset="utf-8">
	<meta name="viewport" content="width=device-width, initial-scale=1.0">

	<title>${esc(title)} — lew42</title>
	<meta name="description" content="${esc(description)}">
	<link rel="canonical" href="${esc(abs)}">
	<link rel="icon" type="image/png" href="/assets/img/favicon.png">

	<meta property="og:type" content="${esc(type)}">
	<meta property="og:site_name" content="lew42">
	<meta property="og:title" content="${esc(title)}">
	<meta property="og:description" content="${esc(description)}">
	<meta property="og:url" content="${esc(abs)}">${image ? `
	<meta property="og:image" content="${esc(site + image)}">` : ""}

	<meta name="twitter:card" content="${image ? "summary_large_image" : "summary"}">
	<meta name="twitter:title" content="${esc(title)}">
	<meta name="twitter:description" content="${esc(description)}">${image ? `
	<meta name="twitter:image" content="${esc(site + image)}">` : ""}

	<!-- …and then the ordinary app. The router reads location.pathname and walks to
	     this post, so the same url that carried the tags above renders the real page. -->
	<script type="module" src="/app.js"></script>
</head>
<body></body>
</html>
`;
}

/* A post that declares no `image:` still unfurls with a picture: the first PNG in its
 * own directory. A FALLBACK, never the rule — the manifest is where a post says which
 * picture represents it, and this exists only so a post full of screenshots does not
 * ship a text-only card because nobody wrote the field. It never reaches the page:
 * what a post draws at the top is `lead: true` in the manifest, and only that. */
async function first_png(dir){
	const files = await readdir(join(here, dir)).catch(() => []);
	const png = files.filter(name => name.toLowerCase().endsWith(".png")).sort()[0];

	return png && "/blog/" + dir + "/" + png;
}

/* Every page with an address of its own: the front, the three section indexes, and
 * one per post. A section index carries `website` rather than `article` — it is a
 * list, and an unfurled card that calls it an article is a small lie. */
const shells = [
	{
		dir: ".",
		html: shell({
			title: "Blog",
			description: "Notes on building a web framework with no build step.",
			url: "/blog/",
			type: "website",
		}),
	},

	...sections.map(section => ({
		dir: section.name,
		html: shell({
			title: section.title,
			description: section.blurb,
			url: "/blog/" + section.name + "/",
			type: "website",
		}),
	})),

	...await Promise.all(listed().map(async post => ({
		dir: slug(post),
		html: shell({
			...post,
			image: post.image ?? await first_png(slug(post)),
			url: "/blog/" + slug(post) + "/",
		}),
	}))),
];

let drift = 0, pending = 0;

for (const { dir, html } of shells){
	const path = join(here, dir, "index.html");

	/* ⚠ NEVER mkdir. An entry in the manifest is what COMMISSIONS a post, so a
	 *   directory that is not there yet is a post somebody is still writing — and
	 *   creating it here would leave a url that serves a meta shell, boots the app,
	 *   and finds no page.js: a blank page with a perfect social card. Report and
	 *   skip; run this again when the post lands. */
	if (!await stat(dirname(path)).catch(() => null)){
		pending++;
		console.log(`pending ${dir}/ — no directory yet`);
		continue;
	}

	const current = await readFile(path, "utf8").catch(() => null);

	if (current === html){ console.log(`ok      ${dir}/index.html`); continue; }

	drift++;

	if (!write){ console.log(`${current === null ? "MISSING" : "STALE  "} ${dir}/index.html`); continue; }

	await writeFile(path, html);
	console.log(`written ${dir}/index.html`);
}

if (pending) console.log(`\n${pending} post(s) commissioned but not written yet.`);

if (drift && !write){
	console.log(`\n${drift} shell(s) out of date — run: node public/blog/meta.mjs --write`);
	process.exitCode = 1;
}
