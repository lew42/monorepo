// Writes moves.md: every sentence of the old CLAUDE.md (base commit) and of the six old skills,
// and the file that holds it word for word now. Computed, never typed; exits 1 if any is lost.
// Run from the repo (or worktree) root: node <this file>
import fs from "node:fs";
import path from "node:path";
import { execSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const BASE = "86901d69d";
const HERE = path.dirname(fileURLToPath(import.meta.url));
const norm = s => s.replace(/\s+/g, " ").trim();
const words = s => s.split(/\s+/).filter(Boolean).length;
const show = f => execSync(`git show ${BASE}:${f}`, { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).replace(/\r\n/g, "\n");
const read = f => fs.readFileSync(f, "utf8").replace(/\r\n/g, "\n");

// Old text: CLAUDE.md, then each moved skill; new homes it may be in.
const HOMES = ["CLAUDE.md", "public/framework/readme.md", "public/framework/doc/rules.md", "public/framework/ai/doc/agent-rules.md", "public/framework/ai/doc/claude-md-archive.md"];
const roles = JSON.parse(read(path.join(HERE, "role-readmes.json")));
const home_text = Object.fromEntries([...HOMES, ...roles.map(r => r.to)].map(f => [f, norm(read(f))]));

const sentences = text => text.split(/\n(?=## )/).flatMap(sec => {
	const head = sec.split("\n")[0].replace(/^#+\s*/, "");
	return sec.split(/\n+/).flatMap(line => line.split(/(?<=[.!?:)])\s+(?=[A-Z*(`"\d])/)).map(norm).filter(s => s.length > 2 && !/^-+$/.test(s)).map(s => ({ head, s }));
});
const strip = s => s.replace(/^(?:[-*]|\d+\.)\s+/, "");
const where = (s, homes) => homes.filter(f => home_text[f].includes(strip(s)) || home_text[f].includes(s));

const out = ["# Moves: old text → where it is now (computed)", "",
	`Generated by \`node ${path.relative(process.cwd(), fileURLToPath(import.meta.url)).replaceAll("\\", "/")}\` from the base commit \`${BASE}\`; never edit by hand. Every sentence of the old \`CLAUDE.md\` and of the six skills that became role readmes is looked up, word for word, in the new files. A sentence found nowhere is a loss and fails the run.`, ""];
let lost = 0;

// Word counts, before → after.
const now = f => fs.existsSync(f) ? words(read(f)) : 0;
const was = f => { try { return words(show(f)); } catch { return 0; } };
out.push("## Word counts, before → after", "", "| File | Before | After |", "|---|---|---|");
for (const f of ["CLAUDE.md", "public/framework/readme.md", "public/framework/ai/readme.md", "public/framework/doc/rules.md", "public/framework/ai/doc/agent-rules.md", "public/framework/ai/doc/records.md", "Servex/agents/roles/readme.md", ...roles.map(r => r.to), ...roles.map(r => r.from)])
	out.push(`| \`${f}\` | ${was(f).toLocaleString()} | ${now(f).toLocaleString()} |`);
out.push("");

// CLAUDE.md, by section.
out.push("## CLAUDE.md, sentence by sentence", "");
let last = null, n = 0;
const counts = {};
for (const { head, s } of sentences(show("CLAUDE.md"))) {
	if (head !== last) { out.push("", `### ${head}`, "", "| Sentence (start) | Now in |", "|---|---|"); last = head; }
	const at = where(s, HOMES);
	const best = at.find(f => f !== "public/framework/ai/doc/claude-md-archive.md") ?? at[0];
	if (!best) lost++;
	counts[best ?? "LOST"] = (counts[best ?? "LOST"] ?? 0) + 1; n++;
	out.push(`| ${s.slice(0, 70).replaceAll("|", "\\|")}${s.length > 70 ? "…" : ""} | ${best ? `\`${best}\`` : "**LOST**"} |`);
}
out.splice(out.indexOf("## CLAUDE.md, sentence by sentence") + 2, 0, `${n} sentences: ` + Object.entries(counts).map(([f, c]) => `${c} in \`${f}\``).join(", ") + ".", "");

// Skills → role readmes: whole-body check, line by line.
out.push("", "## Skills → role readmes", "", "| Skill | Role readme | Lines found / total |", "|---|---|---|");
for (const r of roles) {
	const body = show(r.from).replace(/^---[\s\S]*?\n---\n/, "");
	const lines = body.split("\n").map(norm).filter(Boolean);
	// Relative links were re-based, so compare with link targets removed.
	const unlink = s => s.replace(/\]\([^)]*\)/g, "]");
	const target = unlink(home_text[r.to]);
	const found = lines.filter(l => target.includes(unlink(l))).length;
	if (found < lines.length) lost += lines.length - found;
	out.push(`| \`${r.from}\` | \`${r.to}\` | ${found} / ${lines.length} |`);
}
// The ai readme → itself + doc/records.md: line by line, links ignored (re-based).
{
	const unlink = s => s.replace(/\]\([^)]*\)/g, "]");
	const lines = show("public/framework/ai/readme.md").split("\n").map(norm).filter(Boolean);
	const homes = ["public/framework/ai/readme.md", "public/framework/ai/doc/records.md"];
	const texts = homes.map(f => unlink(norm(read(f))));
	const tally = {}; let gone = [];
	for (const l of lines) { const i = texts.findIndex(t => t.includes(unlink(l))); if (i < 0) gone.push(l); else tally[homes[i]] = (tally[homes[i]] ?? 0) + 1; }
	lost += gone.length;
	out.push("", "## The ai readme → itself and doc/records.md", "", `${lines.length} lines: ` + Object.entries(tally).map(([f, c]) => `${c} in \`${f}\``).join(", ") + (gone.length ? `; **LOST**: ${gone.map(g => g.slice(0, 60)).join(" · ")}` : "; none lost") + ".");
}
fs.writeFileSync(path.join(HERE, "moves.md"), out.join("\n") + "\n");
console.log(`moves.md written; ${n} CLAUDE.md sentences; lost: ${lost}`);
process.exit(lost ? 1 : 0);
