import path from "path"; import { pathToFileURL } from "url";
const here = path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1"));
const repo = path.resolve(here, "../../../../../../../../../../..");
const { default: Browser } = await import(pathToFileURL(path.join(repo, "Server/Browser.mjs")).href);
const browser = await Browser.browser({ args: ["--use-fake-device-for-media-stream", "--use-fake-ui-for-media-stream"] });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true, permissions: ["microphone"] });
const page = await ctx.newPage();
page.on("console", m => console.log("console:", m.text().slice(0, 200)));
page.on("pageerror", e => console.log("pageerror:", String(e).slice(0, 200)));
await page.route(/127\.0\.0\.1:8178/, r => r.request().method() === "GET" ? r.fulfill({ status: 200, body: "ok", headers: { "access-control-allow-origin": "*" } }) : r.fulfill({ status: 200, contentType: "application/json", headers: { "access-control-allow-origin": "*" }, body: '{"text":" hello "}' }));
await page.goto("http://monorepo.localhost/", { waitUntil: "load" });
await page.waitForSelector(".drawer-rail-ai");
await page.click(".drawer-rail-ai");
await page.waitForSelector(".drawer-rail-sheet.on .ux-dictate-widget");
await page.waitForTimeout(3000);
