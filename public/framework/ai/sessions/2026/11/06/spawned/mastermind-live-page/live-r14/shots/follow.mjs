import fs from "node:fs";
import { chromium } from "file:///C:/Users/mike/AppData/Roaming/npm/node_modules/playwright/index.mjs";
const [,, base, root, w = "400", shots = process.env.TEMP] = process.argv;
const D = root + "/public/live/zzfollow", F = D + "/page.jsonl";
fs.mkdirSync(D, { recursive: true });
const L = [{ class: "/live/LivePage.js", title: "Follow probe" }, { tasks: { add: { id: "t1", title: "A task" } } }];
for (let i = 1; i <= 12; i++) L.push({ content: { add: { type: "part-card", id: "c" + i, title: "Card " + i, text: "Some text for card " + i + "." } }, by: "probe", ts: new Date().toISOString() });
fs.writeFileSync(F, L.map(l => JSON.stringify(l)).join("\n") + "\n");
const add = (id) => fs.appendFileSync(F, JSON.stringify({ content: { add: { type: "part-card", id, title: "New " + id, text: "arrived live" } }, by: "probe", ts: new Date().toISOString() }) + "\n");
const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: +w, height: 900 } });
const errs = []; p.on("pageerror", e => errs.push(String(e).slice(0, 200))); p.on("console", m => m.type() === "error" && errs.push(m.text().slice(0, 150)));
await p.goto(base + "/live/zzfollow/", { waitUntil: "networkidle" }); await p.waitForTimeout(2500);
const st = () => p.evaluate(() => { const s = document.querySelector(".active-page .live-scroll"), j = s?.querySelector(".chatbox-jump"), pg = document.querySelector(".pages");
  return { gap: s && Math.round(s.scrollHeight - s.clientHeight - s.scrollTop), btn: j ? (j.hidden ? "hidden" : j.classList.contains("has-new") ? "lit" : "dim") : "none", last: [...s.querySelectorAll(".live-card-title")].map(e => e.textContent).filter(Boolean).pop(), pagesScroll: pg.scrollHeight - pg.clientHeight, status: document.querySelector(".active-page .live-status-bar")?.innerText.replace(/\s+/g, " ") }; });
const log = (k, v) => console.log(k.padEnd(22), JSON.stringify(v));
log("start", await st());
await p.screenshot({ path: shots + "/follow-" + w + "-start.png" });
add("n1"); await p.waitForTimeout(1500); log("new while at bottom", await st());
await p.mouse.move(+w / 2, 400); await p.mouse.wheel(0, -1500); await p.waitForTimeout(600); log("scrolled up", await st());
add("n2"); await p.waitForTimeout(1500); log("new while scrolled up", await st());
await p.screenshot({ path: shots + "/follow-" + w + "-lit.png" });
await p.click(".active-page .chatbox-jump"); await p.waitForTimeout(600); log("tapped down", await st());
add("n3"); await p.waitForTimeout(1500); log("new after relock", await st());
await p.click(".active-page .live-status-bar"); await p.waitForTimeout(300);
await p.screenshot({ path: shots + "/follow-" + w + "-sheet.png" });
log("sheet", await p.evaluate(() => document.querySelector(".active-page .live-status-sheet")?.innerText.replace(/\s+/g, " ")));
console.log("errors:", errs.join(" | ") || "none");
await b.close();
fs.rmSync(F); fs.rmdirSync(D);
