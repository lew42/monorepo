// Figma variables (variables.json) → opt-in CSS custom properties (tokens.css). Why and how: ../doc/token-sync.md
// Run: node public/framework/ext/Figma/tokens/FigmaTokens.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export class FigmaTokens {
	static dir = path.dirname(fileURLToPath(import.meta.url));

	// Figma mode → CSS class; a scheme class also paints its own ground and ink
	static resolution = { Default: "fig-default", Mobile: "fig-mobile", Mega: "fig-mega" };
	static schemes = { "Light BG": "fig-white", "Light gray BG": "fig-gray", "Dark BG": "fig-dark", "Prime BG": "fig-prime" };
	static skip = new Set(["size", "ref"]);   // unfinished experiments in the file, not tokens

	constructor(json) {
		this.json = json;
		this.col = Object.fromEntries(json.collections.map(c => [c.name, c]));
	}

	static load() { return new FigmaTokens(JSON.parse(fs.readFileSync(path.join(this.dir, "variables.json"), "utf8"))); }

	value(v) { return v && typeof v === "object" && v.alias ? `var(--fig-${v.alias})` : typeof v === "number" ? `${v}px` : v; }

	block(selector, vars, mode) {
		const lines = Object.entries(vars).filter(([n]) => !FigmaTokens.skip.has(n)).map(([n, d]) => `\t\t--fig-${n}: ${this.value(d.values[mode])};`);
		return `\t${selector} {\n${lines.join("\n")}\n\t}`;
	}

	css() {
		const { Colors, Text, Resolution } = this.col;
		const out = [];
		out.push(this.block(":root", Colors.vars, Colors.modes[0]));
		// Resolution: Default everywhere, Mobile under 600, Mega from 2560; a class pins a mode like Figma's explicit mode
		out.push(this.block(":root, .fig-default", Resolution.vars, "Default"));
		out.push(`\t@media (max-width: 599px) {\n${this.block(":root", Resolution.vars, "Mobile")}\n\t}`);
		out.push(`\t@media (min-width: 2560px) {\n${this.block(":root", Resolution.vars, "Mega")}\n\t}`);
		out.push(this.block(".fig-mobile", Resolution.vars, "Mobile"));
		out.push(this.block(".fig-mega", Resolution.vars, "Mega"));
		for (const [mode, cls] of Object.entries(FigmaTokens.schemes)) {
			out.push(this.block(`.${cls}`, Text.vars, mode).replace(/\n\t}$/, "\n\t\tbackground: var(--fig-surface);\n\t\tcolor: var(--fig-text);\n\t}"));
		}
		out.push(FigmaTokens.utilities);
		return `/* GENERATED by FigmaTokens.mjs from variables.json (Figma ${this.json.file}, ${this.json.exported}). Do not edit; re-export and re-run.\n   Opt-in: nothing on the site loads this file yet. ../doc/token-sync.md */\n@layer theme {\n${out.join("\n\n")}\n}\n`;
	}

	// the few patterns the Figma kit is built from, by the same names
	static utilities = [
		"\t.fig-card { padding: var(--fig-pad-y) var(--fig-pad-x); border-radius: var(--fig-radius); }",
		"\t.fig-section { padding: var(--fig-section-pad-y) var(--fig-section-pad-x); }",
		"\t.fig-row { padding: var(--fig-small-pad-y) var(--fig-small-pad-x); }",
		"\t.fig-stack { display: flex; flex-direction: column; gap: var(--fig-gap); }",
		"\t.fig-stack > * { margin: 0; }   /* auto layout has no margins: the gap is the only space, as in Figma */",
		"\t.fig-inset { background: rgb(0 0 0 / 0.1); }",
		"\t.fig-dark .fig-lift { background: rgb(255 255 255 / 0.1); }",
		"\t.fig-muted { color: var(--fig-muted); }",
		"\t.fig-accent { color: var(--fig-accent); }",
		"\t.fig-btn { display: inline-flex; align-items: center; justify-content: center; gap: var(--fig-small-pad-x); min-height: 44px; padding: var(--fig-small-pad-y) var(--fig-gap); border: 0; border-radius: var(--fig-radius); font-family: inherit; font-weight: 700; font-size: 14px; line-height: 1.4; letter-spacing: 0.07em; text-transform: uppercase; color: var(--fig-text); background: none; }",
		"\t.fig-btn-primary { background: var(--fig-accent); color: var(--fig-on-accent); }",
		"\t.fig-btn-secondary { background: rgb(0 0 0 / 0.1); }",
	].join("\n");

	write() {
		const file = path.join(FigmaTokens.dir, "tokens.css");
		fs.writeFileSync(file, this.css());
		return file;
	}
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
	console.log("wrote", FigmaTokens.load().write());
}
